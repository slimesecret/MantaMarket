        async function loadCartDropdown() {
            try {
                const res = await fetch('/MantaMarket/public/api/cart.php?action=get');
                const json = await res.json();
                if (!json.success) return;
                updateCartBadge(json.total_count);
                const container = document.getElementById('cartDropdownItems');
                const footer = document.getElementById('cartFooterCount');
                if (footer) footer.textContent = `${json.total_count} Thêm Hàng Vào Giỏ`;
                if (!json.items.length) {
                    container.innerHTML = '<div class="cart-empty">Chưa có sản phẩm nào</div>';
                    return;
                }
                container.innerHTML = json.items.map(item => {
                    const price = parseInt(item.price).toLocaleString('vi-VN') + 'đ';
                    const variant = [item.color, item.size].filter(Boolean).join(', ');
                    const img = item.image_url || 'data:image/svg+xml,<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48"><rect fill="%23eee" width="48" height="48"/></svg>';
                    return `
                <div class="cart-dropdown-item">
                    <img src="${img}" alt="${item.product_name}" onerror="this.src='data:image/svg+xml,<svg xmlns=%22http://www.w3.org/2000/svg%22 width=%2248%22 height=%2248%22><rect fill=%22%23eee%22 width=%2248%22 height=%2248%22/></svg>'">
                    <div class="cart-item-info">
                        <div class="cart-item-name">${item.product_name}</div>
                        ${variant ? `<div class="cart-item-variant">${variant}</div>` : ''}
                    </div>
                    <div class="cart-item-price">${price}</div>
                </div>`;
                }).join('');
            } catch (e) {}
        }

        function updateCartBadge(count) {
            const badge = document.getElementById('cartBadge');
            if (badge) {
                badge.textContent = count > 99 ? '99+' : count;
                badge.style.display = count > 0 ? '' : 'none';
            }
        }
        async function addToCart(productId, variantId = null, quantity = 1) {
            // Kiểm tra login
            if (!document.getElementById('cartBadge')) return;

            const data = new FormData();
            data.append('action', 'add');
            data.append('product_id', productId);
            data.append('quantity', quantity);
            if (variantId) data.append('variant_id', variantId);

            try {
                const res = await fetch('/MantaMarket/public/api/cart.php', {
                    method: 'POST',
                    body: data
                });
                const json = await res.json();

                if (json.success) {
                    updateCartBadge(json.cart_count);
                    showCartToast('Đã thêm vào giỏ hàng!');
                    loadCartDropdown();
                } else {
                    showCartToast(json.message, 'error');
                }
            } catch (e) {
                showCartToast('Lỗi kết nối!', 'error');
            }
        }
        function showCartToast(msg, type = 'success') {
            let t = document.getElementById('cartToast');
            if (!t) {
                t = document.createElement('div');
                t.id = 'cartToast';
                t.style.cssText = `
            position:fixed; top:80px; right:24px; padding:12px 20px;
            border-radius:6px; font-size:14px; font-weight:500; z-index:99999;
            box-shadow:0 4px 16px rgba(0,0,0,.15); transition:opacity .3s;
            color:#fff; display:flex; align-items:center; gap:8px;
        `;
                document.body.appendChild(t);
            }
            t.style.background = type === 'success' ? '#22c55e' : '#ef4444';
            t.innerHTML = type === 'success' ?
                `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="white" stroke-width="2.5"><polyline points="20 6 9 17 4 12"/></svg> ${msg}` :
                `✕ ${msg}`;
            t.style.opacity = '1';
            setTimeout(() => t.style.opacity = '0', 2500);
        }

