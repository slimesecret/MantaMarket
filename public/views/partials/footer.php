(function () {
    var API  = '/MantaMarket/public/api/search_suggest.php';
    var WAIT = 220;
    var timer, lastKw, dd;
 
    /* ---- helpers ---- */
    function esc(s) {
        return String(s ?? '')
            .replace(/&/g,'&amp;').replace(/</g,'&lt;')
            .replace(/>/g,'&gt;').replace(/"/g,'&quot;');
    }
    function hl(text, kw) {
        if (!kw) return esc(text);
        var re = new RegExp('(' + kw.replace(/[.*+?^${}()|[\]\\]/g,'\\$&') + ')', 'gi');
        return esc(text).replace(re,'<span class="sd-hl">$1</span>');
    }
    function fmt(n) { return Number(n).toLocaleString('vi-VN') + 'đ'; }
 
    /* ---- dropdown ---- */
    function getDD(input) {
        if (dd) return dd;
        dd = document.createElement('div');
        dd.className = 'search-dropdown';
        input.closest('.search-bar').appendChild(dd);
        document.addEventListener('click', function(e){
            if (!input.closest('.search-bar').contains(e.target)) hide();
        });
        return dd;
    }
    function show() { dd && dd.classList.add('active'); }
    function hide() { dd && dd.classList.remove('active'); }
 
    /* ---- render ---- */
    function loading(el)       { el.innerHTML = '<div class="sd-loading">Đang tìm kiếm…</div>'; show(); }
    function empty(el, kw)     { el.innerHTML = '<div class="sd-empty">Không tìm thấy "<b>' + esc(kw) + '</b>"</div>'; show(); }
 
    function render(el, data) {
        var kw = data.keyword || '';
        var h  = '';
 
        if (data.categories && data.categories.length) {
            h += '<div class="sd-section-title">Danh mục</div><div class="sd-categories">';
            data.categories.forEach(function(c){
                h += '<button class="sd-cat-chip" onclick="openCategoryPanel(\'' + esc(c.slug) + '\');hideSD();">'
                   + '<svg width="11" height="11" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5">'
                   + '<rect x="3" y="3" width="7" height="7"/><rect x="14" y="3" width="7" height="7"/>'
                   + '<rect x="14" y="14" width="7" height="7"/><rect x="3" y="14" width="7" height="7"/></svg>'
                   + hl(c.name, kw) + '</button>';
            });
            h += '</div>';
        }
 
        if (data.products && data.products.length) {
            h += '<div class="sd-section-title">Sản phẩm</div>';
            data.products.forEach(function(p){
                var thumb = p.image_url
                    ? '<img class="sd-product-thumb" src="' + esc(p.image_url) + '" alt="" loading="lazy">'
                    : '<div class="sd-product-thumb-ph">🛍️</div>';
                var sold = p.sold_count > 0
                    ? '<span class="sd-product-sold">· Đã bán ' + Number(p.sold_count).toLocaleString('vi-VN') + '</span>'
                    : '';
                // Dùng parseInt để chắc chắn id là số nguyên, không bị escHtml encode
                var id = parseInt(p.id, 10);
                h += '<button class="sd-product-item" onclick="openSpPanel(' + id + ');hideSD();">'
                   + thumb
                   + '<div class="sd-product-info">'
                   + '<div class="sd-product-name">' + hl(p.name, kw) + '</div>'
                   + '<div><span class="sd-product-price">' + fmt(p.base_price) + '</span>' + sold + '</div>'
                   + '</div></button>';
            });
            h += '<div class="sd-footer" onclick="doSearchAll(\'' + esc(kw) + '\')">Kết quả tìm kiếm cho "<b>' + esc(kw) + '</b>" &rarr;</div>';
        } else if (!data.categories || !data.categories.length) {
            empty(el, kw); return;
        }
 
        el.innerHTML = h;
        show();
    }
 
    /* ---- fetch ---- */
    async function suggest(input, kw) {
        var el = getDD(input);
        loading(el);
        try {
            var res  = await fetch(API + '?q=' + encodeURIComponent(kw));
            var data = await res.json();
            if (kw !== lastKw) return;
            if (data.error) { el.innerHTML = '<div class="sd-empty">Lỗi: ' + esc(data.error) + '</div>'; show(); return; }
            var hasP = data.products   && data.products.length;
            var hasC = data.categories && data.categories.length;
            if (!hasP && !hasC) { empty(el, kw); return; }
            render(el, data);
        } catch(e) {
            if (dd) { dd.innerHTML = '<div class="sd-empty">Lỗi kết nối.</div>'; show(); }
        }
    }
 
    /* ---- global ---- */
    window.hideSD = hide;
    window.doSearchAll = function(kw) {
        // TODO: thêm URL redirect trang search
        // window.location.href = '/MantaMarket/public/index.php?r=search&q=' + encodeURIComponent(kw);
        hide();
    };
 
    /* ---- init ---- */
    document.addEventListener('DOMContentLoaded', function(){
        var input = document.querySelector('.search-input');
        if (!input) return;
 
        input.addEventListener('input', function(){
            var kw = this.value.trim();
            clearTimeout(timer);
            if (!kw) { hide(); return; }
            lastKw = kw;
            timer  = setTimeout(function(){ suggest(input, kw); }, WAIT);
        });
 
        input.addEventListener('focus', function(){
            if (this.value.trim() && dd && dd.innerHTML) show();
        });
 
        input.addEventListener('keydown', function(e){
            if (e.key === 'Enter')  { window.doSearchAll(this.value.trim()); }
            if (e.key === 'Escape') { hide(); }
        });
 
        // Nút search
        var btn = document.querySelector('.search-btn');
        if (btn) btn.addEventListener('click', function(){
            window.doSearchAll(input.value.trim());
        });
    });
})();
