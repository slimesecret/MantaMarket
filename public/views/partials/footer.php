            const INITIAL_VISIBLE_COUNT = 30;
            const ITEMS_TO_LOAD_PER_CLICK = 12;
            let currentIndex = INITIAL_VISIBLE_COUNT;
            // 1. Ẩn các sản phẩm vượt quá 30 khi vừa load trang
            function hideInitialProducts() {
                if (products.length <= INITIAL_VISIBLE_COUNT) {
                    // Nếu tổng sản phẩm <= 30 thì luôn ẩn nút Xem thêm
                    loadMoreContainer.style.display = 'none';
                    return;
                }
                products.forEach((product, index) => {
                    if (index >= INITIAL_VISIBLE_COUNT) {
                        product.classList.add('hidden-product');
                    }
                });
            }
            // 2. Xử lý sự kiện bấm nút "Xem Thêm"
            btnLoadMore.addEventListener('click', function() {
                let newlyVisibleCount = 0;
                for (let i = currentIndex; i < products.length; i++) {
                    // Hiện sản phẩm và đếm số lượng vừa hiện
                    if (products[i].classList.contains('hidden-product')) {
                        products[i].classList.remove('hidden-product');
                        newlyVisibleCount++;
                        // Dừng lại khi đã hiện đủ số lượng cần load (12 sản phẩm)
                        if (newlyVisibleCount >= ITEMS_TO_LOAD_PER_CLICK) {
                            break;
                        }
                    }
                }
                // Cập nhật lại vị trí index hiện tại
                currentIndex += newlyVisibleCount;
                // 3. Nếu đã hiện hết tất cả sản phẩm -> Ẩn nút "Xem Thêm"
                if (currentIndex >= products.length) {
                    loadMoreContainer.style.display = 'none';
                }
            });
            // Chạy hàm ẩn lúc mới vào trang
            hideInitialProducts();
        });
